export function getStandardGovernorateName(name: string): string {
  if (!name) return "";
  const cleaned = name.trim().toLowerCase();

  const found = EGYPTIAN_GOVERNORATES.find(
    (g) =>
      g.en.toLowerCase() === cleaned ||
      g.en.toLowerCase().replace(/\s+/g, "") === cleaned.replace(/\s+/g, "")
  );
  if (found) return found.en;

  // Normalized matching
  if (cleaned.includes("cairo") || cleaned.includes("قاهر")) return "Cairo";
  if (cleaned.includes("giza") || cleaned.includes("جيز")) return "Giza";
  if (cleaned.includes("alex") || cleaned.includes("إسكندر") || cleaned.includes("اسكندر")) return "Alexandria";
  if (cleaned.includes("qalyub") || cleaned.includes("قليوب")) return "Qalyubia";
  if (cleaned.includes("sharq") || cleaned.includes("شرقي")) return "Sharqia";
  if (cleaned.includes("dakahl") || cleaned.includes("دقهل")) return "Dakahlia";
  if (cleaned.includes("gharbi") || cleaned.includes("غربي")) return "Gharbia";
  if (cleaned.includes("monuf") || cleaned.includes("منوف")) return "Monufia";
  if (cleaned.includes("beheir") || cleaned.includes("بحير")) return "Beheira";
  if (cleaned.includes("kafr") || cleaned.includes("كفر")) return "Kafr El Sheikh";
  if (cleaned.includes("damiet") || cleaned.includes("دمياط")) return "Damietta";
  if (cleaned.includes("port") || cleaned.includes("بورسعيد")) return "Port Said";
  if (cleaned.includes("ismail") || cleaned.includes("اسماعيل") || cleaned.includes("إسماعيل")) return "Ismailia";
  if (cleaned.includes("suez") || cleaned.includes("سويس")) return "Suez";
  if (cleaned.includes("fayoum") || cleaned.includes("فيوم")) return "Fayoum";
  if (cleaned.includes("suef") || cleaned.includes("سويف")) return "Beni Suef";
  if (cleaned.includes("minya") || cleaned.includes("منيا")) return "Minya";
  if (cleaned.includes("asyut") || cleaned.includes("اسيوط") || cleaned.includes("أسيوط")) return "Asyut";
  if (cleaned.includes("sohag") || cleaned.includes("سوهاج")) return "Sohag";
  if (cleaned.includes("qena") || cleaned.includes("قنا")) return "Qena";
  if (cleaned.includes("luxor") || cleaned.includes("أقصر") || cleaned.includes("اقصر")) return "Luxor";
  if (cleaned.includes("aswan") || cleaned.includes("اسوان") || cleaned.includes("أسوان")) return "Aswan";
  if (cleaned.includes("red sea") || cleaned.includes("بحر")) return "Red Sea";
  if (cleaned.includes("matrouh") || cleaned.includes("مطروح")) return "Matrouh";
  if (cleaned.includes("south sinai") || cleaned.includes("جنوب سيناء")) return "South Sinai";
  if (cleaned.includes("north sinai") || cleaned.includes("شمال سيناء")) return "North Sinai";
  if (cleaned.includes("new valley") || cleaned.includes("وادي")) return "New Valley";

  return name.trim();
}

export function searchGovernorates(query: string): EgyptianGovernorate[] {
  const q = query.trim().toLowerCase();
  if (!q) return EGYPTIAN_GOVERNORATES;
  return EGYPTIAN_GOVERNORATES.filter((g) => g.en.toLowerCase().includes(q));
}

export function searchDistricts(governorate: string, query: string): string[] {
  const q = query.trim().toLowerCase();
  const gov = EGYPTIAN_GOVERNORATES.find(
    (g) =>
      g.en.toLowerCase() === governorate.toLowerCase() ||
      getStandardGovernorateName(governorate).toLowerCase() === g.en.toLowerCase()
  );

  const pool = gov ? gov.districts : EGYPTIAN_GOVERNORATES.flatMap((g) => g.districts);
  const uniquePool = Array.from(new Set(pool));

  if (!q) return uniquePool.slice(0, 15);
  return uniquePool.filter((d) => d.toLowerCase().includes(q));
}
